// Bundles data/justices/* (roster, reviewed profile, SCDB voting record) into lib/roster.generated.ts so the
// deployed job reads them from code rather than from files on disk. Re-run after editing a profile.
//   npm run roster:build
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "data/justices";
const justices = readdirSync(dir)
  .map((slug) => {
    const read = (f: string) => (existsSync(join(dir, slug, f)) ? readFileSync(join(dir, slug, f), "utf8") : null);
    const roster = JSON.parse(read("roster.json")!);
    return { ...roster, profile: read("profile.md"), votingRecord: read("voting.md") };
  })
  .sort((a, b) => a.seniority_rank - b.seniority_rank);

writeFileSync(
  "lib/roster.generated.ts",
  `// Generated by scripts/profiles/build-roster.ts from data/justices/*. Do not edit by hand.
export type RosterJustice = { slug: string; name: string; last_name: string; seniority_rank: number; appointed: string; active: boolean; profile: string | null; votingRecord: string | null };
export const ROSTER: RosterJustice[] = ${JSON.stringify(justices, null, 2)};
`,
);
console.log(`Wrote lib/roster.generated.ts with ${justices.length} justices (${justices.filter((j) => j.profile).length} profiles).`);
