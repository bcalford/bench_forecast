// Regenerates supabase/seed.sql from data/justices/<slug>/roster.json (the roster's source of truth).
// Run: npm run seed:build
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../data/justices/", import.meta.url).pathname;
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

const rows = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => JSON.parse(readFileSync(join(dir, d.name, "roster.json"), "utf8")))
  .sort((a, b) => a.seniority_rank - b.seniority_rank);

const values = rows
  .map((j) => `  (${q(j.slug)}, ${q(j.name)}, ${q(j.last_name)}, ${j.seniority_rank}, ${q(j.appointed)}, ${j.active})`)
  .join(",\n");

const sql = `-- Generated by scripts/build-seed.mjs from data/justices/*/roster.json. Do not edit by hand.
insert into justices (slug, name, last_name, seniority_rank, appointed, active) values
${values}
on conflict (slug) do update set
  name = excluded.name, last_name = excluded.last_name, seniority_rank = excluded.seniority_rank,
  appointed = excluded.appointed, active = excluded.active;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} justices.`);
